/**
 * DEVELOPMENT AUDIO PLACEHOLDERS — synthetic test tones, NOT recordings (docs/AUDIO_ENGINE.md §14).
 *
 * The recordings are supplied by the project owner (CLAUDE.md §4). A short, locally generated
 * fallback tone remains available for EVERY production archive entry and every development
 * fixture, so the engine, the spatial mix and the record change run with real buffers. Tones are
 * assigned by ROLE: an archive entry's variant is its catalogue position (A = hero, B…E), a fixture's
 * cycles B, C — never by position in whichever record set is active. The catalog (audioCatalog.ts)
 * uses a tone only for audioAvailability "pending" / "development" and marks it
 * "development-placeholder"; `Track.audioUrl` stays null. In the archive set the visitor sees
 * "Archive audio pending", never "development tone" (FocusOverlay).
 *
 * Files: public/audio/<eraId>/dev-placeholder--<trackId>.wav, generated by `npm run audio:dev`
 * (scripts/build-dev-audio.mjs) from the spec below. Each tone identifies its era AND record by ear:
 * <era number> soft plucks per 2 s bar over a quiet drone, pitch rising per era; variants B…E shift
 * the pitch (fifth, octave, third, fourth) and the pluck offset. Hero tones are unchanged since the
 * audio milestone; fixture tones unchanged since the record-change milestone.
 *
 * Plain TypeScript (no React) so the generator script and Node tests can import it.
 */
import { DEV_TRACKS_BY_ERA, isDevFixture } from "../data/devFixtures.ts";
import { ARCHIVE_TRACKS_BY_ERA } from "../data/tracks.ts";
import { ERA_IDS, type EraId } from "../data/types.ts";

export const DEV_AUDIO_SPEC = {
  /** Mono 16-bit PCM WAV (no encoder needed; decoded by every browser). */
  sampleRate: 22050,
  /** Seamless loop length: four 2 s bars. */
  seconds: 8,
  barSeconds: 2,
  /** Pluck pitch per era, in loop order (G3 A3 B3 C4 D4 E4 F4 G4). */
  frequencies: [196.0, 220.0, 246.94, 261.63, 293.66, 329.63, 349.23, 392.0],
  pluckSpacing: 0.2,
  pluckDecay: 0.25,
  pluckLevel: 0.22,
  droneLevel: 0.04,
  /** Per variant (A = hero, B…E = archive positions 2–5; fixtures B, C): pitch multiplier and pluck offset within the bar (s). */
  variants: [
    { pitch: 1, offset: 0 },
    { pitch: 1.5, offset: 0 },
    { pitch: 2, offset: 0.1 },
    { pitch: 1.25, offset: 0.05 },
    { pitch: 4 / 3, offset: 0.15 },
  ],
} as const;

export const devPlaceholderAudioUrl = (eraId: EraId, trackId: string): string => `/audio/${eraId}/dev-placeholder--${trackId}.wav`;

export interface DevAudioAsset {
  eraId: EraId;
  eraIndex: number;
  trackId: string;
  /** archive = production archive entry (variant = catalogue position − 1); fixture = development fixture. */
  role: "archive" | "fixture";
  /** 0 = A (hero) … 4 = E; fixtures 1, 2, 1, 2 … (B, C, B, C …). */
  variant: number;
  url: string;
}

/** Variant of the `fixtureIndex`-th fixture (0-based) of an era: B, C, B, C … */
export const fixtureVariant = (fixtureIndex: number): number => 1 + (fixtureIndex % 2);

/** Variant of an archive entry at playlist position `position` (0-based): A…E, cycling for longer playlists. */
export const archiveVariant = (position: number): number => position % DEV_AUDIO_SPEC.variants.length;

/** Every record that gets a development tone: each era's archive entries, then its fixtures. Independent of the active record set. */
export const DEV_AUDIO_ASSETS: readonly DevAudioAsset[] = ERA_IDS.flatMap((eraId, eraIndex) => {
  const asset = (trackId: string, role: DevAudioAsset["role"], variant: number): DevAudioAsset => ({ eraId, eraIndex, trackId, role, variant, url: devPlaceholderAudioUrl(eraId, trackId) });
  const fixtures = DEV_TRACKS_BY_ERA[eraId].filter(isDevFixture);
  return [
    ...ARCHIVE_TRACKS_BY_ERA[eraId].map((track, position) => asset(track.id, "archive", archiveVariant(position))),
    ...fixtures.map((track, k) => asset(track.id, "fixture", fixtureVariant(k))),
  ];
});

/** Track id → development tone URL. */
export const DEV_AUDIO_PLACEHOLDERS: Readonly<Record<string, string>> = Object.fromEntries(DEV_AUDIO_ASSETS.map((asset) => [asset.trackId, asset.url]));
